public class Swich_java 
{
	public static void main(String[]args)
	{
		String GT = "Trai";
		switch(GT)
		{
			case"Trai":
				System.out.println("gioi tinh nam");
				break;
			
			case"Nu":
				System.out.println("gioi tinh nu");
				break;
			
			default:
				System.out.println("khong ro gioi tinh");
		}
	}
}

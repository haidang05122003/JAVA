package Quan_ly_sinh_vien_OOP;

public class Lop {
    private String Ten, Khoa;

    public Lop(String ten, String khoa) {
        Ten = ten;
        Khoa = khoa;
    }

    public String getTen() {
        return Ten;
    }

    public void setTen(String ten) {
        Ten = ten;
    }

    public String getKhoa() {
        return Khoa;
    }

    public void setKhoa(String khoa) {
        Khoa = khoa;
    }
}
